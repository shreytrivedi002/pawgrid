#!/usr/bin/env python3
"""Independent build gate + mobile asset synchronization. Run after authoring."""
import gzip
import hashlib
import json
from pathlib import Path
import build_catalog as builder

ROOT=Path(__file__).resolve().parents[1]
payload=(ROOT/'content/catalog.json').read_bytes()
expected=(ROOT/'content/catalog.sha256').read_text().strip()
assert hashlib.sha256(payload).hexdigest()==expected, 'Catalog digest mismatch'
pack=json.loads(payload)
ids=set()
signatures=set()
for level in pack['levels']:
    assert level['levelId'] not in ids, 'Duplicate ID'
    ids.add(level['levelId'])
    errors=builder.ref.validate_level(level)
    assert not errors,(level['levelId'],errors)
    trace=builder.logical_trace(level)
    assert trace is not None, f"Unrated {level['levelId']}"
    assert trace==level['deductionTrace'], f"Trace changed {level['levelId']}"
    sig=builder.signature(level['regions'])
    if level['n']!=4:
        assert sig not in signatures, 'Symmetry duplicate'
        signatures.add(sig)
assert len(pack['journey'])==200
assert len(pack['daily'])>=38
assert all(id in ids for id in pack['journey']+pack['practice']+list(pack['daily'].values()))
mobile=ROOT/'app/assets/content'
mobile.mkdir(parents=True,exist_ok=True)
(mobile/'catalog.json').write_bytes(payload)
(mobile/'catalog.sha256').write_text(expected+'\n')
(mobile/'catalog.fallback.gz').write_bytes(gzip.compress(payload,mtime=0))
(ROOT/'app/lib/data/catalog_digest.dart').write_text("// Generated by tools/validate_catalog.py.\nconst bundledCatalogDigest =\n    '"+expected+"';\n")
print(f"PASS: {len(ids)} unique, connected, hash-verified, H1–H5 deducible boards; 200 Journey, 68 Daily, 30 Practice. Mobile assets and verified fallback synchronized.")
